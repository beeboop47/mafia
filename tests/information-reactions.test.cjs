const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const fixture=fs.readFileSync(path.join(__dirname,'expansion.test.cjs'),'utf8').split('const active=')[0];
const game=new Function('require','__dirname',fixture+'\nreturn game;')(require,__dirname);
function attacked(action){const c=game('none',action);c.recordNightAction(c.playerOf(1),'kill',0);c.state.night.pendingAttacks=[{attackerId:1,targetId:0,sourceAction:'kill'}];c.prepareExtraAttacks();return c;}
for(const [action,expected] of [
  ['identifyAssailant',/Your attacker is Player 1/],['readWeapon',/generated by Kill/],
  ['traceTheirSteps',/recorded reaction was None/],['countThreats',/began tonight with/],
  ['witnessSearch',/began tonight as Mafia/],['readTheirPast',/allegiance was unchanged/]
])test(`${action} gives its result immediately on the existing reaction turn, with no dawn message`,()=>{
  const c=attacked(action);const queue=c.state.night.reactionQueue.map(p=>p.id);
  const result=c.resolveNewReaction(c.playerOf(0),'activate');assert.match(result,expected);assert.doesNotMatch(result,/at dawn|wait|following night/);
  assert.equal(c.playerOf(0).alive,true);assert.equal(c.playerOf(0).used[action],true);assert.match(c.extraNoticesFor(c.playerOf(0)),expected);
  assert.equal(c.playerOf(0).dawnMessages.length,0);assert.deepEqual(c.state.night.reactionQueue.map(p=>p.id),queue);
  c.finishExtraNight();assert.ok(c.state.players.every(p=>p.dawnMessages.length===0));assert.throws(()=>c.resolveNewReaction(c.playerOf(0),'activate'),/No reaction/);
});
test('replacement clues use fixed historical snapshots, not what has happened before the holder’s turn',()=>{
  for(const [action,expected] of [['traceTheirSteps',/recorded reaction was None/],['witnessSearch',/began tonight as Mafia/],['countThreats',/began tonight with no recorded night ability/]]){
    const c=attacked(action);c.playerOf(1).roleId='doctor';c.playerOf(1).roleOverrides={nightReaction:'escape',nightAction:'protect'};
    c.recordNightAction(c.playerOf(1),'protect',4);assert.match(c.resolveNewReaction(c.playerOf(0),'activate'),expected);
  }
});
test('Read Their Past conceals unchanged allegiance and retains attack-time allegiance after later changes',()=>{
  const c=attacked('readTheirPast');c.state.night.signalStart[1].orientation='good';c.playerOf(1).roleOverrides={orientation:'neutral'};
  const result=c.resolveNewReaction(c.playerOf(0),'activate');assert.match(result,/began tonight Good/);assert.match(result,/was Evil when the attack was recorded/);assert.doesNotMatch(result,/Neutral/);
});
test('Lingering Frame validates choices before spending the reaction',()=>{
  const c=attacked('counterframe');assert.throws(()=>c.resolveNewReaction(c.playerOf(0),'choose:missing'),/valid reaction/);
  assert.equal(c.playerOf(0).alive,true);assert.equal(c.state.night.proposedReactionUsed[0],undefined);
  const result=c.resolveNewReaction(c.playerOf(0),'choose:doctor');assert.match(result,/following night/);assert.equal(c.investigationRoleOf(c.playerOf(1),4).title,'Mafia');
  assert.equal(c.playerOf(0).pendingReactionDeceptions[0].round,2);
});
test('Break Their Reaction replaces counterattacks with a next-night reaction block',()=>{
  const c=attacked('lastShot');c.resolveNewReaction(c.playerOf(0),'activate');
  assert.equal(c.playerOf(1).alive,true);assert.equal(c.playerOf(1).disabledReactionRound,2);assert.equal(c.state.night.queuedCounterattacks,undefined);
  c.finishExtraNight();assert.equal(c.playerOf(1).alive,true);assert.ok(c.state.players.every(p=>!p.dawnMessages.length));
});
test('formerly dawn-only results and letters use existing night turns instead',()=>{
  const c=game('deathEcho');c.playerOf(2).alive=false;c.initializeExtraNight();assert.match(c.proposedInfoResult(c.playerOf(0)),/Faction Memory: 1/);
  c.recordExtraChoice(c.playerOf(1),'deadLetter',{targetId:4,text:'Signed message'});
  c.recordExtraChoice(c.playerOf(3),'contingencyNote',{targetId:4,second:'5',text:'Shared message'});
  c.recordExtraChoice(c.playerOf(5),'sealedReply',{targetId:4,text:'A private question'});c.resolveExtraDefenses();c.resolveExtraEffects();
  assert.match(c.extraNoticesFor(c.playerOf(4)),/Signed letter from Player 1/);assert.match(c.extraNoticesFor(c.playerOf(4)),/Anonymous shared note/);
  assert.match(c.extraNoticesFor(c.playerOf(5)),/Shared message/);assert.match(c.extraNoticesFor(c.playerOf(4)),/A private question/);assert.equal(c.state.night.replyRequests.length,0);
  c.finishExtraNight();assert.ok(c.state.players.every(p=>p.dawnMessages.length===0));
});
test('Read Last Night reports prior recorded death immediately, including a revived target',()=>{
  const c=game('predictDeath');c.setPlayerAlive(c.playerOf(2),false);c.setPlayerAlive(c.playerOf(2),true);
  c.state.round=2;c.initializeExtraNight();c.recordExtraChoice(c.playerOf(0),'predictDeath',{targetId:2});
  assert.match(c.proposedInfoResult(c.playerOf(0)),/Player 2 died during the preceding night/);c.finishExtraNight();assert.equal(c.playerOf(0).dawnMessages.length,0);
});
